#!/usr/bin/env python3
"""MicroRhodoDB v1.6.1: one decision per unique sequence.

Finds groups of byte-identical, non-engineered source records (protein.sequence_sha256) whose membership tier or
function call differ in the v1.6.0 database, and writes one decision row per changed field. The rule set was approved
by the curator on 2026-10-24 (referee comment R1-1); this script applies it record by record so that every change is
listed with its old value, new value and rule.

Rules
  M1  a curated decoy (decoy_or_rejected) wins over identical candidate records         -> decoy_or_rejected
  M2  a curated member (typeI_member_curated, E1 with a primary paper) wins             -> typeI_member_curated
  F1  an E1 record gives its identical, uncalled twins an E2 call at identity 1.00
  F2  an E3/E4 call whose identical twin was withdrawn for a motif conflict             -> E5 unassigned (conservative)
  F3  an uncalled twin (E5 unresolved, basis insufficient) of a conflict-withdrawn record -> E5 unassigned
  F4  an uncalled twin (E5 unresolved, basis insufficient) of an unconflicted E3/E4 call -> same call (same motif)
  F5  sensory vs sensory_like at the same level: E3 follows the clade consensus (sensory); E4 takes sensory_like

Usage: python pipeline/v161/identical_sequences_v161.py <v1.6.0 db> <out decisions.tsv>
"""
import sqlite3
import sys

import pandas as pd

DECIDED_BY = "CongJian Li"
DECIDED_AT = "2026-10-24"
APPROVAL = "rule set approved by the curator on 2026-10-24 (referee comment R1-1); per-record rows generated by this script"


def load(db):
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    df = pd.read_sql("""
        SELECT p.sequence_sha256 AS h, p.mrdb_acc, f.source_acc, m.membership_status, m.status_reason,
               f.func_class, f.evidence_level, f.basis, f.e2_ref, f.e2_identity, f.call_conflict,
               f.call_conflict_detail, f.override_rule
        FROM protein p JOIN function_evidence f USING(source_acc) JOIN membership m USING(source_acc)
        WHERE COALESCE(f.is_engineered, 0) = 0 AND p.sequence_sha256 IS NOT NULL""", con)
    con.close()
    return df


def decisions(df):
    out = []

    def change(r, table, field, new, rule, why):
        old = r[field]
        old_s = "" if pd.isna(old) else str(old)
        new_s = "" if new is None else str(new)
        if old_s != new_s:
            out.append(dict(source_acc=r.source_acc, mrdb_acc=r.mrdb_acc, table_name=table, field=field,
                            old_value=old_s, new_value=new_s, rule=rule, rationale=why))

    def set_call(r, src, rule, why):
        for fld in ("func_class", "evidence_level", "call_conflict", "call_conflict_detail"):
            change(r, "function_evidence", fld, src[fld] if not pd.isna(src[fld]) else None, rule, why)
        change(r, "function_evidence", "basis", f"identical_sequence:{src.source_acc}|{src.basis}", rule, why)
        change(r, "function_evidence", "override_rule", "identical_sequence_v161", rule, why)

    groups = df.groupby("h").filter(lambda g: len(g) > 1)
    for h, g in groups.groupby("h", sort=True):
        if g.membership_status.nunique() == 1 and g.func_class.nunique() == 1:
            continue
        g = g.sort_values("source_acc")
        # --- membership
        for status, rule in (("decoy_or_rejected", "M1"), ("typeI_member_curated", "M2")):
            ref = g[g.membership_status == status]
            if len(ref):
                ref = ref.iloc[0]
                for _, r in g[g.membership_status != status].iterrows():
                    why = f"identical sequence to {ref.source_acc} ({status}); one decision per unique sequence"
                    change(r, "membership", "membership_status", status, rule, why)
                    change(r, "membership", "status_reason", f"identical_sequence_v161:{ref.source_acc}", rule, why)
                break
        # --- function
        e1 = g[g.evidence_level == "E1"]
        called = g[g.evidence_level.isin(["E3", "E4"])]
        withdrawn = g[(g.evidence_level == "E5") & (g.func_class == "unassigned")]
        uncalled = g[(g.evidence_level == "E5") & (g.func_class == "unresolved")]
        if g.func_class.nunique() == 1:
            continue  # membership-only difference (handled above)
        if len(e1):
            ref = e1.iloc[0]
            for _, r in uncalled.iterrows():
                why = f"identical sequence to E1 record {ref.source_acc}"
                change(r, "function_evidence", "evidence_level", "E2", "F1", why)
                change(r, "function_evidence", "func_class", ref.func_class, "F1", why)
                change(r, "function_evidence", "basis", f"experimental_ortholog:{ref.source_acc}@1.00:identical_sequence", "F1", why)
                change(r, "function_evidence", "e2_ref", ref.source_acc, "F1", why)
                change(r, "function_evidence", "e2_identity", 1.0, "F1", why)
                change(r, "function_evidence", "call_conflict", ref.call_conflict, "F1", why)
                change(r, "function_evidence", "call_conflict_detail",
                       None if pd.isna(ref.call_conflict_detail) else ref.call_conflict_detail, "F1", why)
                change(r, "function_evidence", "override_rule", "identical_sequence_v161", "F1", why)
        elif len(withdrawn):
            ref = withdrawn.iloc[0]
            for _, r in called.iterrows():
                set_call(r, ref, "F2", f"identical twin {ref.source_acc} carries a legacy label that conflicts with "
                                       f"the shared helix-C motif; the more conservative call is kept")
            for _, r in uncalled.iterrows():
                set_call(r, ref, "F3", f"identical twin {ref.source_acc} was withdrawn for a motif conflict")
        elif called.func_class.nunique() == 1 and len(uncalled):
            ref = called.sort_values(["evidence_level", "source_acc"]).iloc[0]
            for _, r in uncalled.iterrows():
                set_call(r, ref, "F4", f"identical twin {ref.source_acc} has an unconflicted {ref.evidence_level} "
                                       f"call; the sequence and motif are the same")
        elif set(called.func_class) == {"sensory", "sensory_like"} and called.evidence_level.nunique() == 1:
            lvl = called.evidence_level.iloc[0]
            target = "sensory" if lvl == "E3" else "sensory_like"
            why = ("E3: the call follows the clade's E1 consensus (sensory)" if lvl == "E3"
                   else "E4: no characterised member; the weaker class sensory_like is kept")
            for _, r in called[called.func_class != target].iterrows():
                change(r, "function_evidence", "func_class", target, "F5", why)
        else:
            sys.exit(f"identical-sequence group {h[:12]} matches no rule: {g[['source_acc', 'evidence_level', 'func_class']].values.tolist()}")
    d = pd.DataFrame(out)
    d.insert(0, "decision_id", [f"V161-{i:03d}" for i in range(1, len(d) + 1)])
    d["decided_by"], d["decided_at"], d["approval"] = DECIDED_BY, DECIDED_AT, APPROVAL
    return d


if __name__ == "__main__":
    db, out = sys.argv[1], sys.argv[2]
    d = decisions(load(db))
    d.to_csv(out, sep="\t", index=False)
    print(f"{len(d)} field changes on {d.source_acc.nunique()} records; rules {d.groupby('rule').source_acc.nunique().to_dict()}")
