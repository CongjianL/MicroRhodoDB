#!/usr/bin/env python3
"""MicroRhodoDB v1.6.2: per-field decisions from the construction review (pipeline/construction_review/).

Writes one decision row per changed field against the v1.6.1 database. Three decisions were approved on 2026-11-25:

  MOTIF1  helix-C motif for the records that have none (the 105 UniProtKB 2026_03 records): helixC_motif and
          motif_class from tools/helixc_motif.py, which reproduces the stored values for all 5,361 2026_02 records.
          The v1.6.0 conflict rule (mrdb_v160_lib.conflict) is then applied to the record's current call. A new
          conflict is flagged; existing flags are never cleared. A new conflict that the v1.6.0 rule would downgrade
          (an E3/E4 call not based on a curated rule) is not covered by the approval, so the script stops.
  PLACE1  QC flag record_clade.placement_qc_flag for Type-I members and candidates whose current MR_RT_003
          placement is the heliorhodopsin outgroup:
          typeI_status_in_heliorhodopsin_outgroup:<diagnosis>, where diagnosis is
            mr_rt_003_sampling_gap         all MR_RT_003 models give the outgroup; MR_RT_002 placed it in a Type-I clade
            model_sensitive                the LG+G4 or LG+R4 placement differs
            consistent_outgroup_placement  outgroup in every model and on MR_RT_002
          The placement and clade call are unchanged.
  E2M1    an E2 call is kept only when the record's helix-C motif equals that of its E1 reference. Applies to
          non-engineered records (engineered constructs take E2 from their own wild type by the v1.6.0 Option B
          policy). The call becomes E5 unresolved: the E1 reference is a characterised protein of a different
          class from the record's motif reading, so neither line of evidence is taken.

Usage: python pipeline/v162/decisions_v162.py <v1.6.1 db> <PF01036.hmm> <out decisions.tsv>
"""
import os
import sqlite3
import sys
import tempfile

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))
sys.path.insert(0, os.path.join(HERE, "..", "v160"))
sys.path.append(os.path.join(HERE, "..", "construction_review"))   # last: its helixc_motif.py must not shadow tools/
import helixc_motif as hm                                   # noqa: E402
from mrdb_v160_lib import conflict, conflict_exact          # noqa: E402
from consistency_checks import placement_vs_membership      # noqa: E402

DECIDED_BY = "CongJian Li"
DECIDED_AT = "2026-11-25"
APPROVAL = ("approved on 2026-11-25 after the construction review (pipeline/construction_review/); "
            "per-record rows generated by this script")
FLAG_PREFIX = "typeI_status_in_heliorhodopsin_outgroup"


def load(db):
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    fe = pd.read_sql("""SELECT f.*, p.mrdb_acc, p.sequence, m.membership_status
                        FROM function_evidence f JOIN protein p USING(source_acc) JOIN membership m USING(source_acc)
                        ORDER BY f.source_acc""", con)
    rc = pd.read_sql("SELECT source_acc FROM record_clade", con)
    pm = placement_vs_membership(con)
    con.close()
    return fe, rc, pm


def main():
    db, hmm, out = sys.argv[1:4]
    fe, rc, pm = load(db)
    rows = []

    def change(r, table, field, old, new, rule, why):
        old_s = "" if old is None or (isinstance(old, float) and pd.isna(old)) else str(old)
        new_s = "" if new is None or (isinstance(new, float) and pd.isna(new)) else str(new)
        if old_s.endswith(".0") and old_s[:-2].isdigit():
            old_s = old_s[:-2]
        if old_s != new_s:
            rows.append(dict(source_acc=r.source_acc, mrdb_acc=r.mrdb_acc, table_name=table, field=field,
                             old_value=old_s, new_value=new_s, rule=rule, rationale=why))

    # MOTIF1
    todo = fe[fe.helixC_motif.isna()]
    with tempfile.TemporaryDirectory() as wd:
        br = fe.loc[fe.source_acc == hm.BR_ACC, "sequence"].iloc[0].upper()
        d = hm.derive({a: s.upper().replace("*", "") for a, s in zip(todo.source_acc, todo.sequence)}, hmm, br, wd)
    d = d.set_index("source_acc")
    for r in todo.itertuples():
        motif, cls = d.at[r.source_acc, "helixC_motif"], d.at[r.source_acc, "motif_class"]
        why = "helix-C motif missing in v1.6.1; re-derived from sequence by tools/helixc_motif.py"
        change(r, "function_evidence", "helixC_motif", r.helixC_motif, motif, "MOTIF1", why)
        change(r, "function_evidence", "motif_class", r.motif_class, cls, "MOTIF1", why)
        if int(r.call_conflict or 0) == 0 and conflict(r.func_class, cls):
            curated = isinstance(r.basis, str) and r.basis.startswith("curated_rule")
            if r.evidence_level in ("E3", "E4") and not curated:
                sys.exit(f"{r.source_acc}: the new motif makes an E3/E4 call conflict; a downgrade is not approved")
            why_c = (f"the re-derived motif ({motif}, {cls}) conflicts with the {r.evidence_level} call {r.func_class}; "
                     "flagged, not changed (v1.6.0 rule: E1/E2/curated-rule conflicts are flag-only)")
            detail = (f"v14={r.func_class}; motif={cls}; action=flag_only_{r.evidence_level}"
                      + ("_curated_rule" if curated else ""))
            change(r, "function_evidence", "call_conflict", r.call_conflict, 1, "MOTIF1", why_c)
            change(r, "function_evidence", "call_conflict_exact", r.call_conflict_exact,
                   conflict_exact(r.func_class, cls), "MOTIF1", why_c)
            change(r, "function_evidence", "call_conflict_detail", r.call_conflict_detail, detail, "MOTIF1", why_c)

    # PLACE1
    pm = pm[pm.source_acc.isin(rc.source_acc)].merge(fe[["source_acc", "mrdb_acc"]], on="source_acc",
                                                       suffixes=("_pm", ""))
    for r in pm.sort_values("source_acc").itertuples():
        why = (f"{r.membership_status} placed in the heliorhodopsin outgroup on MR_RT_003 (Q.pfam+F+R9, "
               f"placement_qc {r.placement_qc}); LG+G4 {r.call_LG_G4}, LG+R4 {r.call_LG_R4}, "
               f"MR_RT_002 clade {r.mr_rt_002_clade if isinstance(r.mr_rt_002_clade, str) else 'none'}")
        change(r, "record_clade", "placement_qc_flag", None, f"{FLAG_PREFIX}:{r.diagnosis}", "PLACE1", why)

    # E2M1
    motif = fe.set_index("source_acc").helixC_motif
    e2 = fe[(fe.evidence_level == "E2") & (fe.is_engineered.fillna(0) == 0)]
    for r in e2.itertuples():
        ref_motif = motif.get(r.e2_ref)
        if r.helixC_motif == ref_motif:
            continue
        why = (f"E2 from {r.e2_ref} at {r.e2_identity:.3f} identity, but the helix-C motif differs ({r.helixC_motif} vs "
               f"{ref_motif}); the motif reading ({r.motif_class}) and the reference's class ({r.func_class}) disagree, "
               "so the call is withdrawn")
        new = dict(evidence_level="E5", func_class="unresolved",
                   basis=f"e2_motif_mismatch:{r.e2_ref}:{ref_motif}vs{r.helixC_motif}",
                   e2_ref=None, e2_identity=None, override_rule="e2_motif_mismatch_v162")
        new["call_conflict"] = conflict(new["func_class"], r.motif_class)
        new["call_conflict_exact"] = conflict_exact(new["func_class"], r.motif_class)
        new["call_conflict_detail"] = None
        for fld, val in new.items():
            change(r, "function_evidence", fld, getattr(r, fld), val, "E2M1", why)

    df = pd.DataFrame(rows)
    df.insert(0, "decision_id", [f"V162-{i:03d}" for i in range(1, len(df) + 1)])
    df["decided_by"], df["decided_at"], df["approval"] = DECIDED_BY, DECIDED_AT, APPROVAL
    df.to_csv(out, sep="\t", index=False)
    print(f"{len(df)} field changes on {df.source_acc.nunique()} records -> {out}")
    print(df.groupby(["rule", "table_name", "field"]).size().to_string())


if __name__ == "__main__":
    main()
