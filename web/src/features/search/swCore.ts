/**
 * In-browser sequence-similarity search: an exact port of the legacy v1.6.0 browser search
 * (site/app.js, "sequence search" block). Scoring semantics are unchanged:
 *
 *   - query parsing: drop the first line if it starts with ">", join, upper-case, keep [A-Z*];
 *   - 3-mer prefilter: per subject, the number of DISTINCT 3-mers (raw letters) shared with the query;
 *     stable sort by that count (descending, ties keep corpus order); keep the first 300;
 *   - Gotoh affine-gap Smith-Waterman, BLOSUM62, gap open 11, gap extension 1, on those 300 only;
 *   - ranking: score desc, then reviewed (Swiss-Prot) first, then MRDB representative first, then
 *     source accession ascending; top 10 get a full traceback (identity, query/subject coverage).
 *
 * tests/unit/seqsearch.test.ts checks every hit of the 13 golden cases generated by running the
 * unmodified legacy code (web/scripts/legacy_seqsearch_golden.mjs) against site/data.js.
 *
 * PR-5 additions that do not change scores for valid input: input validation (one record only,
 * 20..5,000 residues, nucleotide-like input rejected, warnings for non-standard letters), an integer
 * k-mer implementation of the same prefilter, and aligned strings built along the legacy traceback.
 *
 * This is NOT an exhaustive search and NOT the MicroRhodoDB membership scorer (tools/mrdb_search.py).
 */

export const METHOD = {
  id: "mrdb-browser-sw-v1",
  label: "3-mer prefilter (300 candidates) + Smith-Waterman local alignment (BLOSUM62, gap open 11, gap extension 1), top 10",
  legacy: "identical scoring to the v1.6.0 legacy browser search (site/app.js)",
  kmer: 3,
  prefilter: 300,
  top: 10,
  gapOpen: 11,
  gapExtend: 1,
  minLength: 20,
  maxLength: 5000,
} as const;

