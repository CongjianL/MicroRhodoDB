const GO = METHOD.gapOpen;
const GE = METHOD.gapExtend;

/* char code -> BLOSUM62 row index; anything outside AA scores as X (index 22), as in the legacy code. */
const IDX = new Uint8Array(65536).fill(22);
for (let i = 0; i < AA.length; i++) IDX[AA.charCodeAt(i)] = i;

export function encode(s: string): Uint8Array {
  const out = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++) out[i] = IDX[s.charCodeAt(i)];
  return out;
}

/** Legacy parseQuery(), verbatim semantics. */
export function legacyParse(text: string): string {
  const lines = text.trim().split(/\r?\n/);
  const body = lines[0] && lines[0].startsWith(">") ? lines.slice(1) : lines;
  return body.join("").toUpperCase().replace(/[^A-Z*]/g, "");
}

/* ------------------------------------------------------------------------------------------ validation */

export type QueryError =
  | { code: "empty"; message: string }
  | { code: "multi_record"; message: string; records: number }
  | { code: "too_short"; message: string; length: number }
  | { code: "too_long"; message: string; length: number }
  | { code: "nucleotide"; message: string; fraction: number };

export interface ParsedQuery {
  ok: true;
  sequence: string;
  header: string | null;
  warnings: string[];
}

const STANDARD = new Set("ACDEFGHIKLMNPQRSTVWY");

/**
 * Validate a single protein query. Valid single-record input is parsed exactly as the legacy browser
 * did; only inputs the legacy code would silently mis-handle (several FASTA records concatenated,
 * nucleotide sequences, extremely long text) are rejected with an explanation.
 */
export function parseQuery(text: string): ParsedQuery | { ok: false; error: QueryError } {
  const trimmed = text.trim();
  if (!trimmed) return { ok: false, error: { code: "empty", message: "Paste one protein sequence (plain text or a single FASTA record)." } };
  const lines = trimmed.split(/\r?\n/);
  const headers = lines.filter((l) => l.trimStart().startsWith(">")).length;
  if (headers > 1) {
    return {
      ok: false,
      error: {
        code: "multi_record",
        records: headers,
        message: `The input contains ${headers} FASTA records. The browser search accepts one query at a time; for batch searches use tools/mrdb_search.py with the release database.`,
      },
    };
  }
  if (headers === 1 && !lines[0].startsWith(">")) {
    return {
      ok: false,
      error: { code: "multi_record", records: 2, message: "Text before the FASTA header line would be treated as sequence. Remove it, or paste the sequence only." },
    };
  }
  const header = lines[0].startsWith(">") ? lines[0].slice(1).trim() : null;
  const seq = legacyParse(trimmed);
  if (seq.length < METHOD.minLength) {
    return { ok: false, error: { code: "too_short", length: seq.length, message: `Please enter a protein sequence of at least ${METHOD.minLength} residues (found ${seq.length}).` } };
  }
  if (seq.length > METHOD.maxLength) {
    return {
      ok: false,
      error: {
        code: "too_long",
        length: seq.length,
        message: `The query has ${seq.length.toLocaleString("en-US")} residues; the browser search accepts at most ${METHOD.maxLength.toLocaleString("en-US")} (the longest corpus record has 3,449). Long or multi-domain queries are better served by tools/mrdb_search.py, or trim the query to the rhodopsin domain.`,
      },
    };
  }
  let nuc = 0;
  for (const c of seq) if ("ACGTUN".includes(c)) nuc++;
  const frac = nuc / seq.length;
  if (frac >= 0.9) {
    return {
      ok: false,
      error: { code: "nucleotide", fraction: frac, message: `${Math.round(frac * 100)}% of the letters are A, C, G, T, U or N: this looks like a nucleotide sequence. Translate it to protein first; the search compares protein sequences only.` },
    };
  }
  const warnings: string[] = [];
  const body = header === null ? trimmed : lines.slice(1).join("\n");
  const removed = body.replace(/[A-Za-z*\s\d]/g, "");
  if (removed.length) {
    const kinds = [...new Set(removed)].slice(0, 8).join(" ");
    warnings.push(`${removed.length} non-letter character(s) were ignored (${kinds}); gaps and punctuation are not part of the query.`);
  }
  const ns = new Map<string, number>();
  for (const c of seq) if (!STANDARD.has(c)) ns.set(c, (ns.get(c) ?? 0) + 1);
  if (ns.size) {
    const list = [...ns.entries()].map(([c, n]) => `${c} \u00d7${n}`).join(", ");
    warnings.push(
      `Non-standard residue letters: ${list}. B, Z, X and * use their BLOSUM62 rows; any other letter (e.g. J, O, U) is scored as X.`,
    );
  }
  return { ok: true, sequence: seq, header, warnings };
}

/* ------------------------------------------------------------------------------------------ prefilter */

const kcode = (s: string, i: number) => ((s.charCodeAt(i) & 0x7f) << 14) | ((s.charCodeAt(i + 1) & 0x7f) << 7) | (s.charCodeAt(i + 2) & 0x7f);

/**
 * Distinct shared 3-mer counts, identical to the legacy Set-of-substrings version for ASCII input
 * (corpus sequences and parsed queries are ASCII by construction; non-ASCII subjects are handled by
 * the exact fallback). Returns subject indices of the top `keep` by count, stable for ties.
 */
export class Prefilter {
  private qset = new Uint8Array(1 << 21);
  private stamp = new Uint32Array(1 << 21);
  private gen = 0;

  run(query: string, subjects: string[], keep = METHOD.prefilter): number[] {
    const K = METHOD.kmer;
    this.qset.fill(0);
    const qSub = new Set<string>();
    for (let i = 0; i + K <= query.length; i++) {
      this.qset[kcode(query, i)] = 1;
      qSub.add(query.substr(i, K));
    }
    const counts = new Int32Array(subjects.length);
    for (let idx = 0; idx < subjects.length; idx++) {
      const s = subjects[idx];
      if (!/^[\x00-\x7f]*$/.test(s)) {
        counts[idx] = legacyCount(qSub, s);
        continue;
      }
      const g = ++this.gen;
      if (g === 0xffffffff) {
        this.stamp.fill(0);
        this.gen = 1;
      }
      let c = 0;
      for (let i = 0; i + K <= s.length; i++) {
        const k = kcode(s, i);
        if (this.qset[k] && this.stamp[k] !== this.gen) {
          this.stamp[k] = this.gen;
          c++;
        }
      }
      counts[idx] = c;
    }
    const order = Array.from({ length: subjects.length }, (_, i) => i);
    order.sort((a, b) => counts[b] - counts[a] || a - b); // stable: ties keep corpus order (Array#sort is stable)
    return order.slice(0, keep);
  }
}

function legacyCount(qk: Set<string>, s: string): number {
  let c = 0;
  const seen = new Set<string>();
  for (let i = 0; i + METHOD.kmer <= s.length; i++) {
    const k = s.substr(i, METHOD.kmer);
    if (qk.has(k) && !seen.has(k)) {
      seen.add(k);
      c++;
    }
  }
  return c;
}

/* ------------------------------------------------------------------------------------------ alignment */

/** Gotoh affine-gap Smith-Waterman, score only, O(m) memory (legacy swScore). */
export function swScore(q: Uint8Array, s: Uint8Array): number {
  const m = s.length;
  const H = new Int32Array(m + 1);
  const E = new Int32Array(m + 1).fill(-1e9);
  let best = 0;
  for (let i = 1; i <= q.length; i++) {
    const row = B62[q[i - 1]];
    let diag = 0;
    let Fv = -1e9;
    let Hleft = 0;
    for (let j = 1; j <= m; j++) {
      const up = H[j];
      E[j] = Math.max(E[j] - GE, up - GO);
      Fv = Math.max(Fv - GE, Hleft - GO);
      let h = diag + row[s[j - 1]];
      if (E[j] > h) h = E[j];
      if (Fv > h) h = Fv;
      if (h < 0) h = 0;
      diag = up;
      H[j] = h;
      Hleft = h;
      if (h > best) best = h;
    }
  }
  return best;
}

export interface Alignment {
  score: number;
  identity: number;
  qcov: number;
  scov: number;
  alen: number;
  /** 1-based inclusive coordinates of the aligned region. */
  qStart: number;
  qEnd: number;
  sStart: number;
  sEnd: number;
  /** Aligned strings (same length): query, midline ("|" identical, "+" positive score, " " otherwise), subject. */
  qAln: string;
  mid: string;
  sAln: string;
}

/** Full-matrix Smith-Waterman with the legacy traceback (swAlign); aligned strings follow the same path. */
export function swAlign(q: Uint8Array, s: Uint8Array, qStr: string, sStr: string): Alignment {
  const n = q.length;
  const m = s.length;
  const W = m + 1;
  const NEG = -1e9;
  const H = new Int32Array((n + 1) * W);
  const E = new Int32Array((n + 1) * W).fill(NEG);
  const Fm = new Int32Array((n + 1) * W).fill(NEG);
  let best = 0;
  let bi = 0;
  let bj = 0;
  for (let i = 1; i <= n; i++) {
    const row = B62[q[i - 1]];
    for (let j = 1; j <= m; j++) {
      const k = i * W + j;
      E[k] = Math.max(E[k - 1] - GE, H[k - 1] - GO);
      Fm[k] = Math.max(Fm[k - W] - GE, H[k - W] - GO);
      const h = Math.max(0, H[k - W - 1] + row[s[j - 1]], E[k], Fm[k]);
      H[k] = h;
      if (h > best) {
        best = h;
        bi = i;
        bj = j;
      }
    }
  }
  let i = bi;
  let j = bj;
  let state = 0;
  let ident = 0;
  let alen = 0;
  let qs = bi;
  let ss = bj;
  const qa: string[] = [];
  const ma: string[] = [];
  const sa: string[] = [];
  while (i > 0 && j > 0) {
    const k = i * W + j;
    if (state === 0) {
      if (H[k] === 0) break;
      const sc = B62[q[i - 1]][s[j - 1]];
      if (H[k] === H[k - W - 1] + sc) {
        const same = q[i - 1] === s[j - 1];
        if (same) ident++;
        alen++;
        qs = i;
        ss = j;
        qa.push(qStr[i - 1]);
        sa.push(sStr[j - 1]);
        ma.push(same ? "|" : sc > 0 ? "+" : " ");
        i--;
        j--;
        continue;
      }
      if (H[k] === E[k]) {
        state = 1;
        continue;
      }
      state = 2;
      continue;
    }
    if (state === 1) {
      alen++;
      ss = j;
      qa.push("-");
      sa.push(sStr[j - 1]);
      ma.push(" ");
      if (E[k] === H[k - 1] - GO) state = 0;
      j--;
      continue;
    }
    alen++;
    qs = i;
    qa.push(qStr[i - 1]);
    sa.push("-");
    ma.push(" ");
    if (Fm[k] === H[k - W] - GO) state = 0;
    i--;
  }
  return {
    score: best,
    identity: alen ? ident / alen : 0,
    qcov: (bi - qs + 1) / n,
    scov: (bj - ss + 1) / m,
    alen,
    qStart: qs,
    qEnd: bi,
    sStart: ss,
    sEnd: bj,
    qAln: qa.reverse().join(""),
    mid: ma.reverse().join(""),
    sAln: sa.reverse().join(""),
  };
}

/* ------------------------------------------------------------------------------------------ search */

export interface Corpus {
  accs: string[];
  seqs: string[];
  /** Tie-break flags (records-index reviewed / is_mrdb_representative), 0 or 1. */
  reviewed: Uint8Array;
  rep: Uint8Array;
}

export interface Hit extends Alignment {
  rank: number;
  idx: number;
  source_acc: string;
}

export interface SearchResult {
  queryLength: number;
  nSubjects: number;
  prefiltered: number[];
  hits: Hit[];
}

export type Progress = (phase: "prefilter" | "align" | "traceback", done: number, total: number) => void;

/** Run the full legacy pipeline on a validated query sequence. `shouldStop` allows cooperative cancellation. */
export function search(seq: string, corpus: Corpus, pf: Prefilter, progress?: Progress, shouldStop?: () => boolean): SearchResult {
  const q = encode(seq);
  progress?.("prefilter", 0, corpus.seqs.length);
  const pre = pf.run(seq, corpus.seqs);
  progress?.("prefilter", corpus.seqs.length, corpus.seqs.length);
  const scored: { idx: number; score: number }[] = [];
  for (let k = 0; k < pre.length; k++) {
    if (shouldStop?.()) throw new Error("cancelled");
    const idx = pre[k];
    scored.push({ idx, score: swScore(q, encode(corpus.seqs[idx])) });
    if (k % 20 === 19 || k === pre.length - 1) progress?.("align", k + 1, pre.length);
  }
  const R = corpus;
  scored.sort(
    (a, b) =>
      b.score - a.score ||
      R.reviewed[b.idx] - R.reviewed[a.idx] ||
      R.rep[b.idx] - R.rep[a.idx] ||
      (R.accs[a.idx] < R.accs[b.idx] ? -1 : 1),
  );
  const hits = scored.slice(0, METHOD.top).map((h, k) => {
    progress?.("traceback", k, Math.min(METHOD.top, scored.length));
    const a = swAlign(q, encode(corpus.seqs[h.idx]), seq, corpus.seqs[h.idx]);
    return { ...a, rank: k + 1, idx: h.idx, source_acc: corpus.accs[h.idx] };
  });
  return { queryLength: seq.length, nSubjects: corpus.seqs.length, prefiltered: pre, hits };
}

/** Parse corpus.fasta (">SOURCE MRDB" headers, one sequence line per record) preserving order. */
export function parseCorpus(fa: string): { accs: string[]; seqs: string[] } {
  const accs: string[] = [];
  const seqs: string[] = [];
  let buf: string[] | null = null;
  for (const line of fa.split("\n")) {
    if (line.startsWith(">")) {
      if (buf) seqs.push(buf.join(""));
      accs.push(line.slice(1).split(/\s+/)[0]);
      buf = [];
    } else if (buf && line) buf.push(line.trim());
  }
  if (buf) seqs.push(buf.join(""));
  return { accs, seqs };
}

/**
 * Join corpus.fasta with the records-index tie-break flags. The two files are written by the exporter
 * in the same row order; any mismatch is an error (never a silent re-ordering).
 */
export function buildCorpus(parsed: { accs: string[]; seqs: string[] }, index: { accs: string[]; reviewed: ArrayLike<number>; rep: ArrayLike<number> }): Corpus {
  if (parsed.accs.length !== index.accs.length) throw new Error(`corpus.fasta has ${parsed.accs.length} records, records-index has ${index.accs.length}`);
  for (let i = 0; i < parsed.accs.length; i++) {
    if (parsed.accs[i] !== index.accs[i]) throw new Error(`corpus.fasta record ${i + 1} is ${parsed.accs[i]}, records-index row is ${index.accs[i]}`);
  }
  return { accs: parsed.accs, seqs: parsed.seqs, reviewed: Uint8Array.from(index.reviewed), rep: Uint8Array.from(index.rep) };
}
