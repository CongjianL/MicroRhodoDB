#!/usr/bin/env python3
"""PR-5 reconciliation table: every metric, distribution and crosstab in summary.json, its denominator, and the
result of replaying its stored SQL against the read-only v1.6.0 SQLite.

Usage (repository root): python web/scripts/pr5_reconciliation.py --out docs/website/pr5
Writes reconciliation.json and reconciliation.md. Exit 1 if any replay or denominator check fails.
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import json
import re
import sqlite3
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DB = REPO / "releases/v1.6.0/db/microrhododb_v1.6.0.sqlite"
DATA = REPO / "web/public/data/v1.6.0"
PHYLUM = re.compile(r"(?:^|, )([^,]+?) \(phylum\)")


def replay_dist(con, d):
    rows = con.execute(d["sql"]).fetchall()
    if d.get("derivation") and len(rows[0]) == 1:
        c = collections.Counter()
        for (lin,) in rows:
            m = PHYLUM.findall(lin or "")
            c[m[0] if m else None] += 1
        got = dict(c)
    else:
        got = {(str(r[0]) if r[0] is not None else None): r[-1] for r in rows}
    exp = {i["key"]: i["value"] for i in d["items"]}
    return sorted(got.values()) == sorted(exp.values()) and sum(got.values()) == d["total"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    s = json.loads((DATA / "summary.json").read_text())
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    rows, ok = [], True
    for m in s["metrics"]:
        got = con.execute(m["sql"]).fetchone()[0] if m.get("sql") else None
        r = {"kind": "metric", "id": m["id"], "value": m["value"], "denominator": (m.get("denominator") or {}).get("id"),
             "sql_replay": None if got is None else got == m["value"]}
        rows.append(r)
    for d in s["distributions"]:
        tot = sum(i["value"] for i in d["items"])
        rep = replay_dist(con, d) if d.get("sql") else None
        rows.append({"kind": "distribution", "id": d["id"], "value": tot, "denominator": d["denominator"]["id"],
                     "denominator_value": d["denominator"]["value"], "sums_to_denominator": tot == d["denominator"]["value"],
                     "sql_replay": rep})
    for x in s["crosstabs"]:
        tot = sum(c["value"] for c in x["cells"])
        got = sorted(r[2] for r in con.execute(x["sql"]).fetchall())
        rows.append({"kind": "crosstab", "id": x["id"], "value": tot, "denominator": x["denominator"]["id"],
                     "denominator_value": x["denominator"]["value"], "sums_to_denominator": tot == x["denominator"]["value"],
                     "sql_replay": got == sorted(c["value"] for c in x["cells"])})
    for r in rows:
        if r.get("sql_replay") is False or r.get("sums_to_denominator") is False:
            ok = False
    db_sha = hashlib.sha256(DB.read_bytes()).hexdigest()
    (out / "reconciliation.json").write_text(json.dumps({"db_sha256": db_sha, "all_ok": ok, "rows": rows}, indent=1) + "\n")
    yn = lambda v: "n/a" if v is None else ("yes" if v else "NO")  # noqa: E731
    md = ["# PR-5 reconciliation (summary.json vs the read-only v1.6.0 SQLite)", "",
          f"Generated by `web/scripts/pr5_reconciliation.py`. DB SHA-256 `{db_sha}`. All checks pass: **{yn(ok)}**.", "",
          "Frozen anchors: 5,466 source records = 5,460 counted + 6 engineered; 5,299 MRDB accessions; E1 88 counted / 91 total; "
          "4,468 members + candidates, of which 3,821 clade-confident; watchlist 181 (separate table, never added to any corpus count).", "",
          "| Kind | ID | Value / total | Denominator | Sums to denominator | Stored SQL replays exactly |", "|---|---|---|---|---|---|"]
    for r in rows:
        den = f"{r['denominator']} ({r['denominator_value']:,})" if r.get("denominator_value") is not None else (r["denominator"] or "")
        md.append(f"| {r['kind']} | `{r['id']}` | {r['value']:,} | {den} | {yn(r.get('sums_to_denominator'))} | {yn(r['sql_replay'])} |")
    (out / "reconciliation.md").write_text("\n".join(md) + "\n")
    print(f"{len(rows)} rows; all_ok={ok}")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
