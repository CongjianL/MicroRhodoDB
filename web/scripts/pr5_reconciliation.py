#!/usr/bin/env python3
"""Reconciliation table: every metric, distribution and crosstab in summary.json, its denominator, and the
result of a strict keyed replay against the read-only v1.6.0 SQLite (PR-5a; see summary_reconcile.py).

Usage (repository root): python web/scripts/pr5_reconciliation.py --out docs/website/pr5
Writes reconciliation.json and reconciliation.md. Exit 1 if any replay or denominator check fails.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sqlite3
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DB = REPO / "releases/v1.6.0/db/microrhododb_v1.6.0.sqlite"
DATA = REPO / "web/public/data/v1.6.0"
sys.path.insert(0, str(Path(__file__).resolve().parent))
import summary_reconcile as R  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    s = json.loads((DATA / "summary.json").read_text())
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    rows = R.reconcile(con, s, REPO)
    n_sql, n_derived = R.counts(rows)
    ok = all(r["ok"] for r in rows) and (n_sql, n_derived) == (R.EXPECTED_SQL_ITEMS, R.EXPECTED_DERIVED_ITEMS)
    db_sha = hashlib.sha256(DB.read_bytes()).hexdigest()
    (out / "reconciliation.json").write_text(json.dumps(
        {"db_sha256": db_sha, "all_ok": ok, "sql_replayed": n_sql, "independently_derived": n_derived,
         "comparison": "keyed (exact key sets incl. null categories, duplicate keys rejected, value per key, totals)",
         "rows": rows}, indent=1) + "\n")
    yn = lambda v: "yes" if v else "NO"  # noqa: E731
    md = ["# Reconciliation of summary.json with the read-only v1.6.0 SQLite (PR-5a, keyed)", "",
          f"Generated by `web/scripts/pr5_reconciliation.py` (logic in `web/scripts/summary_reconcile.py`). DB SHA-256 `{db_sha}`.", "",
          f"**{n_sql} SQL-replayed items + {n_derived} independently derived item = {len(rows)} items. All exact: {yn(ok)}.**", "",
          "Distributions and crosstabs are compared as complete keyed mappings: identical key sets (a null / missing category "
          "is a key of its own), identical count per key, no duplicate keys in the replayed rows or the exported items, and "
          "totals equal to the denominator. `ncbi_phylum_counted` replays its stored SQL and applies the stored derivation "
          "regex; `tip_role` has no SQL and is derived independently from `refpkg/MR_RT_003/tips.tsv`.", "",
          "Frozen anchors: 5,466 source records = 5,460 counted + 6 engineered; 5,299 MRDB accessions; E1 88 counted / 91 total; "
          "4,468 members + candidates, of which 3,821 clade-confident; watchlist 181 (separate table, never added to any corpus count).", "",
          "| Kind | ID | Total | Denominator | Method | Exact |", "|---|---|---|---|---|---|"]
    for r in rows:
        den = f"{r['denominator']} ({r['denominator_value']:,})" if r.get("denominator_value") is not None else (r["denominator"] or "")
        md.append(f"| {r['kind']} | `{r['id']}` | {r['total']:,} | {den} | {r['method']} | {yn(r['ok'])}{'' if r['ok'] else ': ' + '; '.join(r['problems'])} |")
    (out / "reconciliation.md").write_text("\n".join(md) + "\n")
    print(f"{len(rows)} items ({n_sql} SQL-replayed + {n_derived} derived); all_ok={ok}")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
