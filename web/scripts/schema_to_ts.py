#!/usr/bin/env python3
"""Generate web/src/data/types.ts from web/src/data/schemas/web-data.schema.json
and (PR-7c.2) web/src/data/habitatTypes.ts from web/src/data/schemas/habitat.schema.json.

The JSON Schemas are the single source of truth for the static data contract;
the TypeScript types are derived mechanically so they cannot drift.

    python web/scripts/schema_to_ts.py            # write types.ts and habitatTypes.ts
    python web/scripts/schema_to_ts.py --check    # exit 1 if either file is stale
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "web/src/data/schemas/web-data.schema.json"
OUT = ROOT / "web/src/data/types.ts"
HABITAT_SCHEMA = ROOT / "web/src/data/schemas/habitat.schema.json"
HABITAT_OUT = ROOT / "web/src/data/habitatTypes.ts"
HEADERS = {
    OUT: ["// AUTO-GENERATED by web/scripts/schema_to_ts.py from",
          "// web/src/data/schemas/web-data.schema.json. Do not edit by hand.",
          "// MicroRhodoDB static data contract (PR-1)."],
    HABITAT_OUT: ["// AUTO-GENERATED by web/scripts/schema_to_ts.py from",
                  "// web/src/data/schemas/habitat.schema.json. Do not edit by hand.",
                  "// MicroRhodoDB habitat sidecar contract (PR-7c.2)."],
}
TARGETS = ((SCHEMA, OUT), (HABITAT_SCHEMA, HABITAT_OUT))
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _key(k: str) -> str:
    return k if IDENT.match(k) else json.dumps(k)


def _lit(v) -> str:
    return json.dumps(v, ensure_ascii=False)


def ts(s, ind: int = 0) -> str:
    """Translate one JSON-Schema node into a TypeScript type expression."""
    if s is True or s == {}:
        return "unknown"
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return _lit(s["const"])
    if "enum" in s:
        return " | ".join(_lit(v) for v in s["enum"])
    if "anyOf" in s or "oneOf" in s:
        parts = [ts(x, ind) for x in s.get("anyOf", s.get("oneOf"))]
        return " | ".join(dict.fromkeys(parts))
    if "allOf" in s:
        parts = [ts(x, ind) for x in s["allOf"]]
        extra = {k: v for k, v in s.items() if k != "allOf"}
        if extra.get("properties"):
            parts.append(ts(extra, ind))
        return " & ".join(f"({p})" for p in parts)
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts({**s, "type": x}, ind) for x in t)
    if t == "null":
        return "null"
    if t == "boolean":
        return "boolean"
    if t in ("integer", "number"):
        return "number"
    if t == "string":
        return "string"
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts(x, ind) for x in s["prefixItems"]) + "]"
        inner = ts(s.get("items", True), ind)
        return f"Array<{inner}>"
    if t == "object" or "properties" in s:
        props = s.get("properties", {})
        req = set(s.get("required", []))
        ap = s.get("additionalProperties", True)
        if not props:
            if ap is False:
                return "Record<string, never>"
            return f"Record<string, {ts(ap, ind)}>"
        pad = "  " * (ind + 1)
        lines = ["{"]
        for k in sorted(props):
            opt = "" if k in req else "?"
            lines.append(f"{pad}readonly {_key(k)}{opt}: {ts(props[k], ind + 1)};")
        if ap not in (False, True) and ap != {}:
            lines.append(f"{pad}readonly [key: string]: {ts(ap, ind + 1)};")
        lines.append("  " * ind + "}")
        return "\n".join(lines)
    return "unknown"


def generate(schema_path: Path = SCHEMA, out_path: Path = OUT) -> str:
    schema = json.loads(schema_path.read_text())
    out = [*HEADERS[out_path], ""]
    for name in sorted(schema["$defs"]):
        d = schema["$defs"][name]
        body = ts(d, 0)
        if body.startswith("{"):
            out.append(f"export interface {name} {body}")
        else:
            out.append(f"export type {name} = {body};")
        out.append("")
    out.append("/** Glob (relative to the data root) -> payload type. */")
    out.append("export interface DataFiles {" if out_path == OUT else "export interface HabitatDataFiles {")
    for glob, name in sorted(schema["x-files"].items()):
        out.append(f"  {json.dumps(glob)}: {name};")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rc = 0
    for schema_path, out_path in TARGETS:
        text = generate(schema_path, out_path)
        if a.check:
            if not out_path.exists() or out_path.read_text() != text:
                print(f"STALE: {out_path.relative_to(ROOT)} does not match the schema", file=sys.stderr)
                rc = 1
            else:
                print(f"{out_path.name} is up to date")
            continue
        out_path.write_text(text)
        print(f"wrote {out_path.relative_to(ROOT)} ({len(text)} bytes)")
    return rc


if __name__ == "__main__":
    sys.exit(main())
