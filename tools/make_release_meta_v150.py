#!/usr/bin/env python
"""Assemble the curated MicroRhodoDB v1.5.0 release directory from a finished build.

Steps (idempotent; never touches releases/v1.4.0):
  1. copy build DBs into releases/v1.5.0/db/
  2. tables/membership_assignments_v150.tsv  <- SELECT * FROM v_master
  3. meta/schema_v150.sql                    <- sqlite_master DDL
  4. run tests/test_v150_release.py against the release DB -> validation/{pytest raw, JSON}
  5. meta/build_manifest_v150.json, meta/release_boundaries_v150.json (no placeholders)
  6. meta/superseded_build_v150_pre_curation.json (hashes of the never-tagged pre-curation build)
The browser is rebuilt separately with tools/build_browser.py; SHA256SUMS is written last,
after the release documents are final.

Usage: python tools/make_release_meta_v150.py <build_dir> <repo_dir> <superseded_dir>
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sqlite3
import subprocess
import sys
import xml.etree.ElementTree as ET

import pandas as pd

BUILD, REPO, OLD = sys.argv[1:4]
REL = f"{REPO}/releases/v1.5.0"
DB = f"{REL}/db/microrhododb_v1.5.0.sqlite"
ENV = f"{REL}/db/microrhododb_v1.5.0_env_pilot.sqlite"
TODAY = dt.date.today().isoformat()


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def dump(obj, p):
    with open(p, "w") as f:
        json.dump(obj, f, indent=1, ensure_ascii=False)
        f.write("\n")


# ---- 1. DBs
for n in ("microrhododb_v1.5.0.sqlite", "microrhododb_v1.5.0_env_pilot.sqlite"):
    shutil.copyfile(f"{BUILD}/{n}", f"{REL}/db/{n}")
    assert sha(f"{BUILD}/{n}") == sha(f"{REL}/db/{n}"), n
con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
q = lambda s: pd.read_sql(s, con)

# ---- 2. membership table
vm = q("SELECT * FROM v_master ORDER BY source_acc")
vm.to_csv(f"{REL}/tables/membership_assignments_v150.tsv", sep="\t", index=False)

# ---- 3. schema
ddl = q("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
        "ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, name")
with open(f"{REL}/meta/schema_v150.sql", "w") as f:
    f.write("-- MicroRhodoDB v1.5.0 authoritative schema (curated build, curator sign-off 2026-10-06)\n")
    for s in ddl["sql"]:
        f.write(s.strip() + ";\n\n")

# ---- 4. tests
os.makedirs(f"{REL}/validation", exist_ok=True)
junit = f"{BUILD}/pytest_v150_junit.xml"
env = dict(os.environ, MRDB_DB=DB, MRDB_REPO=REPO)
r = subprocess.run([sys.executable, "-m", "pytest", "-v", "tests/test_v150_release.py", f"--junitxml={junit}"],
                   cwd=REPO, env=env, capture_output=True, text=True)
open(f"{REL}/validation/pytest_v150_raw_output.txt", "w").write(r.stdout + r.stderr)
res = []
for tc in ET.parse(junit).getroot().iter("testcase"):
    st, det = "PASS", "passed"
    for tag, lab in (("failure", "FAIL"), ("error", "ERROR"), ("skipped", "SKIP")):
        e = tc.find(tag)
        if e is not None:
            st, det = lab, (e.get("message") or "")[:500]
    res.append({"test": f"{tc.get('classname')}::{tc.get('name')}", "status": st, "detail": det})
cnt = {k: sum(x["status"] == k for x in res) for k in ("PASS", "FAIL", "ERROR", "SKIP")}
pytest_ver = subprocess.run([sys.executable, "-m", "pytest", "--version"], capture_output=True, text=True).stdout.strip()
dump({"release": "1.5.0", "db": "releases/v1.5.0/db/microrhododb_v1.5.0.sqlite",
      "db_sha256": sha(DB),
      "source_test_suite": "tests/test_v150_release.py (run via: MRDB_DB=<this db> MRDB_REPO=<repo root> pytest tests/test_v150_release.py)",
      "runner": f"{pytest_ver}; python {sys.version.split()[0]}",
      "format_note": "Generated by tools/make_release_meta_v150.py from pytest --junitxml output; one entry per pytest test function.",
      "run_date": TODAY,
      "n_pass": cnt["PASS"], "n_fail": cnt["FAIL"], "n_error": cnt["ERROR"], "n_skip": cnt["SKIP"],
      "n_total": len(res), "results": res}, f"{REL}/validation/validation_v150.json")
if r.returncode != 0:
    print(r.stdout[-3000:])
    sys.exit("release tests failed")

# ---- shared numbers
tables = q("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")["name"]
counts = {t: int(con.execute(f'SELECT COUNT(*) FROM "{t}"').fetchone()[0]) for t in tables}
rm = dict(con.execute("SELECT key, value FROM release_metadata WHERE release = '1.5.0'").fetchall())
assert rm.get("database_release") == "1.5.0" and rm.get("schema_revision") == "v150.1", rm
ev = q("SELECT evidence_level, COUNT(*) n FROM function_evidence GROUP BY 1").set_index("evidence_level")["n"].to_dict()
dec = q("SELECT decision, COUNT(*) n FROM curator_spotcheck_decision GROUP BY 1").set_index("decision")["n"].to_dict()
n_dec = int(sum(dec.values()))
mb = q("SELECT * FROM motif_benchmark")
member = vm.membership_status.isin(["typeI_member_core", "typeI_member_architecture_supported"])
cand = vm.membership_status.isin(["typeI_candidate", "typeI_candidate_architecture_supported", "typeI_candidate_unresolved"])
conf = vm.clade_id.fillna("").ne("")
tent = ~conf & vm.tentative_clade_id.fillna("").ne("")


def cov(mask):
    return {"n": int(mask.sum()), "confident_clade": int((mask & conf).sum()),
            "confident_pct": round(100 * (mask & conf).sum() / mask.sum(), 1),
            "tentative_only": int((mask & tent).sum()), "neither": int((mask & ~conf & ~tent).sum())}


coverage = {"members": cov(member), "members_plus_candidates": cov(member | cand), "all_records": cov(vm.index == vm.index)}
spec_n = counts["spectral_audit"]

old_man = json.load(open(f"{OLD}/release_v1.5.0/meta/build_manifest_v150.json"))
old_bnd = json.load(open(f"{OLD}/release_v1.5.0/meta/release_boundaries_v150.json"))
old_sums = f"{OLD}/release_v1.5.0/SHA256SUMS"

signoff = {"curator": "CongJian Li", "date": "2026-10-06", "items_reviewed": n_dec, "items_signed": n_dec,
           "decision_counts": dec, "approval": "five review batches approved, no exceptions",
           "decision_table": "curator_spotcheck_decision (also curation/spotcheck_decisions_v150.tsv)",
           "signed_sheet": "curation/spotcheck_sheet_v150_signed.tsv"}

# ---- 5a. manifest
man = dict(old_man)
man.update({
    "release_date": TODAY, "schema_revision": rm.get("schema_revision", "v150.1"),
    "base_release": rm.get("base_release", "1.4.0"), "built_at": rm.get("built", TODAY),
    "db_sha256": sha(DB), "db_bytes": os.path.getsize(DB),
    "env_pilot_db_sha256": sha(ENV), "env_pilot_db_bytes": os.path.getsize(ENV),
    "n_tables": len(counts), "table_counts": counts,
    "release_suite": {"db": "releases/v1.5.0/db/microrhododb_v1.5.0.sqlite", "n_pass": cnt["PASS"],
                      "n_fail": cnt["FAIL"], "n_error": cnt["ERROR"], "n_skip": cnt["SKIP"],
                      "n_total": len(res), "results": "<see validation/validation_v150.json>"},
    "recovery_probes_regression": ("not run for v1.5.0: the v1.4.0 recovery probes P1-P9 query the v1.4 "
                                   "table names, which v1.5.0 renames to legacy_*; superseded by the "
                                   f"{len(res)}-test release suite tests/test_v150_release.py "
                                   f"({cnt['PASS']}/{len(res)} pass on this DB)."),
    "curator_signoff": signoff,
    "evidence_ladder": {k: int(v) for k, v in sorted(ev.items())},
    "superseded_build": "meta/superseded_build_v150_pre_curation.json",
})
man["tools"] = dict(old_man["tools"])
man["tools"]["_source"] = ("workflow/envs/mrdb.lock.yml (pinned conda lock). Release tests run with "
                           f"{pytest_ver} from the same environment.")
comp = {k: dict(v) for k, v in old_man["components"].items()}
comp["function_evidence"].update({
    "source_data": "characterized_protein + record_clade + motifs + signed curator spot-check decisions",
    "algorithm": comp["function_evidence"]["algorithm"] + "; E1 requires e1_eligible (curator decision not "
                 "downgrade_E1/annotate_only, and >=1 active supporting publication link when links exist)",
    "params": "curation/spotcheck_decisions_v150.tsv, publication_replacements_v150.tsv, "
              "assertion_link_replacements_v150.tsv, field_corrections_v150.tsv, charset_class_overrides.tsv",
    "built_at": TODAY})
comp["record_clade"].update({"algorithm": comp["record_clade"]["algorithm"] + "; consensus uses E1-eligible records only",
                             "built_at": TODAY})
comp["clade"]["algorithm"] += "; n_records_assigned recomputed from corpus record_clade at build time"
comp["clade"]["built_at"] = TODAY
comp["curator_spotcheck_decision"] = {"source_data": "curation/spotcheck_decisions_v150.tsv", "script": "build_v150.py",
                                      "algorithm": "verbatim import of the signed 65-row decision table",
                                      "params": "", "upstream_deps": "", "built_at": TODAY}
comp["func_class_definition"] = {"source_data": "wp5_evidence.py EXP2V14 vocabulary", "script": "build_v150.py",
                                 "algorithm": "controlled vocabulary for func_class incl. photoreceptor_unassigned",
                                 "params": "", "upstream_deps": "", "built_at": TODAY}
man["components"] = comp
man["code"] = dict(old_man["code"], curator_spotcheck_decision="curation_v150.py; build_v150.py",
                   function_evidence="wp5_evidence.py; curation_v150.py", release_assembly="tools/make_release_meta_v150.py")
dump(man, f"{REL}/meta/build_manifest_v150.json")

# ---- 5b. boundaries
b = dict(old_bnd)
b["database_release"] = rm.get("database_release", "1.5.0")
b["schema_revision"] = rm.get("schema_revision", "v150.1")
b["base_release"] = rm.get("base_release", "1.4.0")
b["uniprot_release"] = ("unchanged from v1.4.0: UniProtKB 2026_02 base corpus + 2026_03 delta harvested "
                        "2026-10-01; no new harvest in v1.5.0")
b["append_only_contract"] = (
    "v1.5.0 is a restructuring release, not strictly additive over v1.4.0: v1.4 tables are retained "
    "read-only under legacy_* names (legacy external metrics partially recomputed under Wilson CIs: "
    "sensitivity/specificity only); "
    "curator corrections to tier_a_assertion/tier_a_evidence/characterized_protein are applied in place "
    "with the original values preserved in v150_original_values and the curated fields listed in "
    "v150_corrected_fields. The v1.4.0 release file is immutable and unchanged (its SHA256SUMS verify).")
fs = dict(b["feature_status"])
fs["implemented"] = list(fs["implemented"]) + [
    f"curator spot-check sign-off: {n_dec}/{n_dec} items signed (CongJian Li, 2026-10-06); "
    "decisions stored in curator_spotcheck_decision and applied to assertion_publication "
    "(is_active, counts_as_support, link_role) and to the E1 eligibility rule",
    "func_class_definition: controlled func_class vocabulary incl. photoreceptor_unassigned "
    "(experimentally photoactive, no ion transport demonstrated; CryoR2-type)",
    "tentative clade layer: v_master.tentative_clade_id/name for records without a confident clade whose "
    "placement is clade_call='assigned' with clade_call_qc='distant_assigned' (browser: 'distant placement, "
    "low confidence', opt-in filter; CLI: nn_tentative_clade_*). Not written to record_clade.",
]
fs["not_in_scope"] = [
    "re-computation of any frozen nondeterministic layer (MMseqs2 clusters, MR_RT_003 tree and placements, "
    "v1.2 scores, WP3 external/holdout evaluation) - these are byte-identical to the pre-curation build",
    "backfilling record_clade from distant (low-confidence) placements; these are exposed only as the "
    "tentative clade layer",
    "functional/spectral annotation of new accessions beyond seed-homology, motif and clade evidence",
]
b["feature_status"] = fs
lim = [x for x in old_bnd["known_limitations"] if not x.startswith("ROOT-CAUSED")]
mc, mm = coverage["members"], coverage["members_plus_candidates"]
lim += [
    ("Named-clade coverage (v_master.clade_id, confident assignments only): members "
     f"{mc['confident_clade']}/{mc['n']} ({mc['confident_pct']}%); members + candidates "
     f"{mm['confident_clade']}/{mm['n']} ({mm['confident_pct']}%), with a further {mm['tentative_only']} "
     "records carrying only a tentative (distant, low-confidence) clade. An earlier draft figure of 96.8% "
     "and the claim that 727 records were wrongly unassigned are retracted: those records' placements are "
     "QC-flagged distant_assigned, and record_clade correctly withholds a confident clade."),
    ("clade.n_records_assigned is recomputed from corpus record_clade at build time; the earlier cached "
     "counts also included non-corpus placements (5 level-1 clades differed)."),
    ("E1 is withheld from H2EZZ6 (no primary functional publication for the Pleodorina starrii sequence; "
     "now E3) and D2RRQ8 (accession-mapping conflict; annotate-only, now E5). The CryoR2-type trio "
     "(A0ABF7PQ03, A0ABF7PQ05, A0AC62AE26) is classed photoreceptor_unassigned and kept in the motif "
     "benchmark, where a pump call is scored as incorrect."),
    (f"Spectral audit restricted to E1-eligible records (n={spec_n})."),
]
b["known_limitations"] = lim
b["clade_coverage"] = coverage
b["curator_signoff"] = signoff
dump(b, f"{REL}/meta/release_boundaries_v150.json")

# ---- 6. superseded build record
dump({"label": "v1.5.0 pre-curation build (never tagged or published)",
      "superseded_on": TODAY,
      "reason": ("rebuilt in place after the curator spot-check sign-off (65/65 items): publication links "
                 "replaced/dropped, field corrections, E1 eligibility rule, CryoR2 photoreceptor_unassigned "
                 "class, clade cache recount, tentative clade layer. Tree, placements and WP3 outputs unchanged."),
      "db_sha256": old_man["db_sha256"], "db_bytes": old_man["db_bytes"],
      "env_pilot_db_sha256": old_man["env_pilot_db_sha256"],
      "SHA256SUMS_sha256": sha(old_sums),
      "evidence_ladder_old": {"E1": 86, "E2": 120, "E3": 1387, "E4": 1358, "E5": 2515},
      "replacement_db_sha256": sha(DB)}, f"{REL}/meta/superseded_build_v150_pre_curation.json")

print(json.dumps({"db": sha(DB), "env": sha(ENV), "tests": cnt, "n_tables": len(counts),
                  "evidence": man["evidence_ladder"], "coverage": coverage, "decisions": dec,
                  "motif_rows": len(mb), "spectral_n": spec_n}, indent=1))
